"""SM90 m64nNk16 f32.f16.f16 SS WGMMA codegen CPU regression tests.

Pins the ``ir.wgmma.f32.f16.f16.m64nnk16_ss`` family:

- the fixed-N named intrinsics ``wgmma_m64n{64,128,256}k16_f16`` (and their
  bf16 siblings), generated by ``_make_codegen_wgmma_ss`` and registered in
  the sm90 backend ``language_exports`` — each must lower to exactly one
  legal ``wgmma.mma_async.sync.aligned.m64n{n}k16.f32.{t}.{t}`` PTX opcode
  with ``n//2`` read-write f32 accumulator constraints and the trans/scale
  immediates baked into the helper name; and
- the generic-N ``wgmma_mma_async_ss`` f16 dispatch, whose tile-N immediate
  must be validated against the PTX whitelist (multiples of 8 in [8, 256])
  before any asm text is composed.

All checks are pure CPU codegen: the frontend is compiled to CUDA source
and the emitted text is inspected. When ``nvcc`` is on PATH one probe is
additionally compiled with ``-gencode arch=compute_90a,code=sm_90a`` as a
ptxas legality acceptance gate (no device is used).
"""

import os
import re
import shutil
import subprocess
import tempfile
import unittest

import little_kernel as lk
import little_kernel.language as ll
import little_kernel.backends.nv.sm90.language.intrin.wgmma as wgmma
from little_kernel.core.passes import PASSES
from little_kernel.backends.nv.common.codegen.emitter import codegen_cuda
from little_kernel.language.builtin_base import BUILTIN_ATTR

FIXED_N = (64, 128, 256)


def _exec_kernel_module(src):
    """Compile kernel source through a fresh on-disk module so the kernel
    sees a real source file (inspect.getsource) as in normal frontend use."""
    # The file must outlive the returned kernel: compilation is lazy and
    # re-reads the source via inspect.getsource at compile() time.
    with tempfile.NamedTemporaryFile("w", suffix=".py", delete=False) as f:
        f.write(src)
        path = f.name
    ns = {"__name__": os.path.basename(path)[:-3]}
    with open(path) as f:
        code = compile(f.read(), path, "exec")
    exec(code, ns)
    kernel_name = next(k for k, v in ns.items() if isinstance(v, lk.core.compile.LLKernel))
    return ns[kernel_name]


def _compile_fixed_n_probe(intrin_name, n):
    """Build and CUDA-compile a probe kernel calling a fixed-N SS builtin."""
    src = ("import little_kernel as lk\n"
           "import little_kernel.language as ll\n"
           "@lk.ll_kernel(backend='cuda', is_entry=True)\n"
           "def _probe(a: ll.Tensor[ll.float16], "
           "out: ll.Tensor[ll.float32]) -> ll.void:\n"
           f"    acc = ll.alloc_local_memory('acc', ll.float32, {n // 2})\n"
           f"    ll.{intrin_name}(acc, 0, 0, 0, 0, 1)\n"
           "    out[ll.threadIdx_x()] = acc[0]\n")
    return _exec_kernel_module(src).compile(PASSES["cuda"], codegen_cuda)


class TestFixedNF16Exports(unittest.TestCase):
    """Fixed-N f16 names are builtins reachable from the ll namespace."""

    def test_f16_names_exported(self):
        for n in FIXED_N:
            name = f"wgmma_m64n{n}k16_f16"
            with self.subTest(name=name):
                self.assertTrue(hasattr(ll, name), f"language namespace misses {name}")
                self.assertTrue(getattr(getattr(ll, name), BUILTIN_ATTR, False))

    def test_bf16_names_exported(self):
        for n in FIXED_N:
            self.assertTrue(hasattr(ll, f"wgmma_m64n{n}k16_bf16"))


class TestFixedNF16CodegenTemplate(unittest.TestCase):
    """Direct codegen: opcode, accumulator arity, and baked immediates."""

    def test_f16_opcode_and_accumulator_arity(self):
        for n in FIXED_N:
            codegen = getattr(wgmma, f"codegen_wgmma_m64n{n}k16_f16")
            with self.subTest(n=n):
                b = codegen("acc", "da", "db", 0, 0, 1)
                opcodes = set(re.findall(r"wgmma\.mma_async[^\s\"\\]*", b.body))
                self.assertEqual(opcodes, {f"wgmma.mma_async.sync.aligned.m64n{n}k16.f32.f16.f16"})
                # n//2 f32 accumulators, read-write ("+f" constraints)
                self.assertEqual(b.body.count('"+f"'), n // 2)
                # scale_d=1 accumulate, trans_a=trans_b=0 immediates
                self.assertIn("p,1,1,0,0;", b.body)

    def test_immediates_baked_into_helper_name(self):
        # Different immediate combinations must produce distinct helpers so
        # call sites never share a definition with the wrong immediates.
        b_default = wgmma.codegen_wgmma_m64n64k16_f16("acc", "da", "db", 0, 0, 1)
        b_trans = wgmma.codegen_wgmma_m64n64k16_f16("acc", "da", "db", 1, 1, 1)
        self.assertIn("wgmma_m64n64k16_f16_a0b0d1_fn(", b_default.body)
        self.assertIn("wgmma_m64n64k16_f16_a1b1d1_fn(", b_trans.body)
        self.assertIn("p,1,1,1,1;", b_trans.body)

    def test_scale_d_zero_overwrites(self):
        b = wgmma.codegen_wgmma_m64n64k16_f16("acc", "da", "db", 0, 0, 0)
        self.assertIn("setp.ne.b32 p, 0, 0;", b.body)
        self.assertIn("wgmma_m64n64k16_f16_a0b0d0_fn(", b.body)

    def test_bf16_sibling_parity(self):
        for n in FIXED_N:
            codegen = getattr(wgmma, f"codegen_wgmma_m64n{n}k16_bf16")
            with self.subTest(n=n):
                b = codegen("acc", "da", "db", 0, 0, 1)
                self.assertIn(f"wgmma.mma_async.sync.aligned.m64n{n}k16.f32.bf16.bf16", b.body)
                self.assertEqual(b.body.count('"+f"'), n // 2)


class TestFixedNF16Legality(unittest.TestCase):
    """Counterexamples: PTX immediates are literal 0/1, enforced before any
    asm text is composed."""

    def test_trans_flag_two_rejected(self):
        with self.assertRaises(ValueError):
            wgmma.codegen_wgmma_m64n64k16_f16("acc", "da", "db", 2, 0, 1)
        with self.assertRaises(ValueError):
            wgmma.codegen_wgmma_m64n64k16_f16("acc", "da", "db", 0, 2, 1)

    def test_scale_d_two_rejected(self):
        with self.assertRaises(ValueError):
            wgmma.codegen_wgmma_m64n64k16_f16("acc", "da", "db", 0, 0, 2)

    def test_non_integer_flag_rejected(self):
        with self.assertRaises(ValueError):
            wgmma.codegen_wgmma_m64n64k16_f16("acc", "da", "db", "zero", 0, 1)


class TestFixedNF16EndToEnd(unittest.TestCase):
    """Full frontend compile: each fixed-N f16 name lowers to exactly one
    legal f16 wgmma opcode in the emitted CUDA source."""

    def test_family_lowering(self):
        for n in FIXED_N:
            name = f"wgmma_m64n{n}k16_f16"
            with self.subTest(name=name):
                src = _compile_fixed_n_probe(name, n)
                ptx = sorted(set(re.findall(r"wgmma\.mma_async[^\s\"\\]*", src)))
                self.assertEqual(ptx, [f"wgmma.mma_async.sync.aligned.m64n{n}k16.f32.f16.f16"])
                self.assertEqual(src.count('"+f"'), n // 2)
                self.assertRegex(src, r"p,1,1,0,0;")

    def test_bf16_parity_lowering(self):
        for n in FIXED_N:
            name = f"wgmma_m64n{n}k16_bf16"
            with self.subTest(name=name):
                src = _compile_fixed_n_probe(name, n)
                ptx = sorted(set(re.findall(r"wgmma\.mma_async[^\s\"\\]*", src)))
                self.assertEqual(ptx, [f"wgmma.mma_async.sync.aligned.m64n{n}k16.f32.bf16.bf16"])


class TestGenericNSSDispatchLegality(unittest.TestCase):
    """The generic-N wgmma_mma_async_ss f16 dispatch validates the tile-N
    immediate against the PTX whitelist before composing asm text."""

    def test_whitelist_boundaries_accepted(self):
        for n in (8, 64, 256):
            with self.subTest(n=n):
                b = wgmma.codegen_wgmma_mma_async_ss("acc", "da", "db", n, dtype="f16")
                self.assertIn("wgmma.mma_async.sync.aligned."
                              f"m64n{n}k16.f32.f16.f16", b.body)
                self.assertEqual(b.body.count('"+f"'), n // 2)

    def test_out_of_range_n_rejected(self):
        for bad_n in (0, 7, 264, 100):
            with self.subTest(n=bad_n):
                with self.assertRaises(ValueError):
                    wgmma.codegen_wgmma_mma_async_ss("acc", "da", "db", bad_n, dtype="f16")

    def test_non_integer_n_rejected(self):
        for bad_n in (None, 64.5):
            with self.subTest(n=bad_n):
                with self.assertRaises(ValueError):
                    wgmma.codegen_wgmma_mma_async_ss("acc", "da", "db", bad_n, dtype="f16")

    def test_non_f16f32_dtype_rejected(self):
        with self.assertRaises(ValueError):
            wgmma.codegen_wgmma_mma_async_ss("acc", "da", "db", 64, dtype="tf32")


@unittest.skipUnless(shutil.which("nvcc"), "nvcc not on PATH; skipping sm_90a acceptance gate")
class TestNvccSm90aAcceptance(unittest.TestCase):
    """CPU-side nvcc acceptance: the emitted inline PTX must be legal for
    sm_90a (ptxas parses it); no device is used."""

    def _compile_sm90a(self, source, label):
        with tempfile.TemporaryDirectory() as td:
            src = os.path.join(td, f"{label}.cu")
            obj = os.path.join(td, f"{label}.o")
            with open(src, "w") as f:
                f.write(source)
            proc = subprocess.run(
                [shutil.which("nvcc"), "-c", "-gencode", "arch=compute_90a,code=sm_90a", "-std=c++17", src, "-o", obj],
                capture_output=True, text=True, check=False)
            self.assertEqual(proc.returncode, 0, f"nvcc sm_90a rejected {label}:\n{proc.stderr}")
            self.assertTrue(os.path.exists(obj))

    def test_fixed_n_f16_family_accepted(self):
        for n in FIXED_N:
            name = f"wgmma_m64n{n}k16_f16"
            with self.subTest(name=name):
                self._compile_sm90a(_compile_fixed_n_probe(name, n), f"{name}_probe")


if __name__ == "__main__":
    unittest.main()
