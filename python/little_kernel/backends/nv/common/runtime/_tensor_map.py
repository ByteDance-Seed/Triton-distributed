"""Host storage for the CUDA tensor-map ABI, independent of tensor libraries."""
import ctypes


class CUtensorMap(ctypes.Structure):
    """The Driver's 128-byte by-value descriptor representation.

    Driver encode operations additionally require aligned allocation; that
    policy belongs to tma_descriptor._new_aligned_tensor_map.
    """
    _fields_ = [("data", ctypes.c_ubyte * 128)]
