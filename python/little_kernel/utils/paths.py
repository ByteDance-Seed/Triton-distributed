"""Resolve a source checkout from an explicitly supplied file, never a fixed depth."""
from pathlib import Path


def repository_root(source_file) -> Path:
    source = Path(source_file).resolve()
    for path in (source.parent, *source.parents):
        if (path / "pyproject.toml").is_file():
            return path
    raise FileNotFoundError(f"No source checkout containing {source}")
